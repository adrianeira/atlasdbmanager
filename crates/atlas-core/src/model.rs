use crate::Secret;
use serde::{Deserialize, Serialize};

/// Modo TLS no estilo do libpq. `VerifyFull` é o recomendado para hosts remotos (spec §42.3).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "kebab-case")]
pub enum SslMode {
    #[default]
    Disable,
    Prefer,
    /// Criptografa sem validar o certificado (aviso na UI).
    Require,
    /// Valida a cadeia, sem conferir o nome do host.
    VerifyCa,
    /// Valida cadeia e nome do host.
    VerifyFull,
}

/// Parâmetros para abrir uma conexão. A senha só vive em memória (o cofre do SO chega no próximo passo).
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ConnectionParams {
    pub host: String,
    pub port: u16,
    pub database: String,
    pub user: String,
    #[serde(default)]
    pub password: Secret,
    #[serde(default)]
    pub ssl_mode: SslMode,
    #[serde(default = "default_connect_timeout")]
    pub connect_timeout_secs: u64,
}

fn default_connect_timeout() -> u64 {
    15
}

/// Uma coluna de ordenação de `table_rows`. `descending = true` ⇒ DESC.
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct OrderBy {
    pub column: String,
    #[serde(default)]
    pub descending: bool,
}

/// Filtro aplicado a `table_rows`: expressão pronta de WHERE, montada pela interface com
/// identificadores entre aspas duplas e valores já quotados/cast ao tipo correto. Fica anexado
/// à query via protocolo simples (sem parâmetros binários) — mesmo caminho de `execute`.
#[derive(Debug, Clone, Deserialize, Default)]
#[serde(rename_all = "camelCase")]
pub struct TableFilter {
    pub expr: String,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ServerInfo {
    /// Versão legível (ex.: "18.0").
    pub version: String,
    /// Versão numérica (ex.: 90619, 180000) usada nos gates de capacidade.
    pub version_num: i32,
    pub current_database: String,
    pub current_user: String,
    /// `Some(true)` quando a sessão está usando TLS; `None` se não foi possível verificar.
    pub tls: Option<bool>,
    pub latency_ms: u64,
}

