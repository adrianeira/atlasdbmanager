//! Dump SQL do Firebird: o DDL é montado a partir das tabelas de sistema (o Firebird não tem `SHOW CREATE`) e os dados saem como
//! `INSERT`, num script que o `isql` e o Atlas executam de volta. A ordem é: geradores, tabelas e views; os dados; e só então chaves
//! estrangeiras, índices, rotinas e gatilhos (para a carga não disparar gatilhos nem esbarrar em chaves). Corpos de gatilhos e rotinas
//! saem entre `SET TERM ^ ;` e `SET TERM ; ^`.

use super::{Conn, map_err, meta, quote_ident};
use atlas_core::{ColumnInfo, DatabaseError, TableDetail};

/// O que entra no dump.
#[derive(Debug, Default)]
pub struct DumpPlan {
    /// Geradores, tabelas e views (com os `DROP` antes, quando pedido).
    pub pre_data: Vec<String>,
    /// Chaves estrangeiras, índices, rotinas, gatilhos e valores dos geradores: depois dos dados.
    pub post_data: Vec<String>,
    /// Tabelas cujos dados entram.
    pub data_tables: Vec<DumpTable>,
    /// Quantos objetos o dump tem.
    pub objects: usize,
}

#[derive(Debug, Clone)]
pub struct DumpTable {
    pub name: String,
    /// Colunas que recebem dados (sem as calculadas), com o tipo.
    pub columns: Vec<(String, String)>,
}

/// O comando entre `SET TERM`, para corpos com `;`.
fn block(stmt: &str) -> String {
    format!("SET TERM ^ ;\n{}^\nSET TERM ; ^", stmt.trim_end_matches(';').trim_end())
}

fn column_line(c: &ColumnInfo) -> String {
    let name = quote_ident(&c.name);
    if c.generated.is_some() {
        return format!("{name} COMPUTED BY {}", c.default.clone().unwrap_or_else(|| "(NULL)".into()));
    }
    let mut line = format!("{name} {}", c.formatted_type);
    // Numeração por identidade (a do gerador + gatilho vem do gatilho e do gerador).
    if c.identity.is_some() && c.auto_source.is_none() {
        line.push_str(" GENERATED BY DEFAULT AS IDENTITY");
    }
    if let Some(d) = &c.default {
        if c.identity.is_none() {
            line.push_str(&format!(" DEFAULT {d}"));
        }
    }
    if c.not_null {
        line.push_str(" NOT NULL");
    }
    line
}

/// O `CREATE TABLE` (chave primária, uniques e checks dentro) de uma tabela lida.
pub(crate) fn create_table(table: &str, d: &TableDetail) -> String {
    let mut lines: Vec<String> = d.columns.iter().map(column_line).collect();
    let mut keys: Vec<&ColumnInfo> = d.columns.iter().filter(|c| c.key.is_some()).collect();
    keys.sort_by_key(|c| c.key);
    if !keys.is_empty() {
        let pk_name = d.constraints.iter().find(|c| c.kind == "p").map(|c| c.name.clone());
        let list = keys.iter().map(|k| quote_ident(&k.name)).collect::<Vec<_>>().join(", ");
        // Nomes gerados pelo servidor (`INTEG_12`) não valem em outro banco: só se mantém o nome escolhido pelo usuário.
        lines.push(match pk_name.filter(|n| !n.starts_with("INTEG_")) {
            Some(n) => format!("CONSTRAINT {} PRIMARY KEY ({list})", quote_ident(&n)),
            None => format!("PRIMARY KEY ({list})"),
        });
    }
    for c in d.constraints.iter().filter(|c| c.kind == "u") {
        let fields = c.fields.split(", ").map(|f| quote_ident(f.trim())).collect::<Vec<_>>().join(", ");
        lines.push(if c.name.starts_with("INTEG_") { format!("UNIQUE ({fields})") } else { format!("CONSTRAINT {} UNIQUE ({fields})", quote_ident(&c.name)) });
    }
    for c in d.constraints.iter().filter(|c| c.kind == "c") {
        let text = c.definition.trim();
        lines.push(if c.name.starts_with("INTEG_") { text.to_string() } else { format!("CONSTRAINT {} {}", quote_ident(&c.name), text) });
    }
    format!("CREATE TABLE {} (\n  {}\n);", quote_ident(table), lines.join(",\n  "))
}

fn foreign_keys(table: &str, d: &TableDetail) -> Vec<String> {
    d.constraints
        .iter()
        .filter(|c| c.kind == "f")
        .map(|c| {
            let list = |s: &str| s.split(", ").map(|f| quote_ident(f.trim())).collect::<Vec<_>>().join(", ");
            let name = if c.name.starts_with("INTEG_") { String::new() } else { format!("CONSTRAINT {} ", quote_ident(&c.name)) };
            let mut text = format!(
                "ALTER TABLE {} ADD {name}FOREIGN KEY ({}) REFERENCES {} ({})",
                quote_ident(table),
                list(&c.fields),
                quote_ident(c.ref_table.as_deref().unwrap_or_default()),
                list(c.ref_fields.as_deref().unwrap_or_default())
            );
            if let Some(a) = c.on_update.as_deref().filter(|a| *a != "RESTRICT" && *a != "NO ACTION") {
                text.push_str(&format!(" ON UPDATE {a}"));
            }
            if let Some(a) = c.on_delete.as_deref().filter(|a| *a != "RESTRICT" && *a != "NO ACTION") {
                text.push_str(&format!(" ON DELETE {a}"));
            }
            text.push(';');
            text
        })
        .collect()
}

/// Um comando de apagar que só roda se o objeto existe (o `DROP ... IF EXISTS` só chega no Firebird 5): confere o catálogo antes.
fn guarded_drop(catalog: &str, column: &str, drop: &str, name: &str) -> String {
    let lit = |s: &str| format!("'{}'", s.replace('\'', "''"));
    format!("EXECUTE BLOCK AS BEGIN IF (EXISTS(SELECT 1 FROM {catalog} WHERE {column} = {})) THEN EXECUTE STATEMENT {}; END;", lit(name), lit(drop))
}

fn gen_value(conn: &mut Conn, generator: &str) -> Result<i64, DatabaseError> {
    let rows = meta::query(conn, &format!("SELECT GEN_ID({}, 0) FROM RDB$DATABASE", quote_ident(generator)), vec![])?;
    Ok(rows.first().and_then(|r| r.first().cloned().flatten()).and_then(|v| v.parse().ok()).unwrap_or(0))
}

/// O plano do dump do banco: `tables` e `views` escolhidos (`None` = todos) e `clean` para o `DROP` antes de cada objeto.
pub(crate) fn plan_on(conn: &mut Conn, tables: Option<&[String]>, views: Option<&[String]>, functions: Option<&[String]>, clean: bool) -> Result<DumpPlan, DatabaseError> {
    let objects = meta::list_objects_on(conn)?;
    let v3 = meta::is_v3(conn);
    let wanted = |list: Option<&[String]>, name: &str| list.is_none_or(|l| l.iter().any(|n| n == name));
    let table_names: Vec<String> = objects.tables.iter().filter(|t| wanted(tables, &t.name)).map(|t| t.name.clone()).collect();
    let view_names: Vec<String> = objects.views.iter().filter(|t| wanted(views, &t.name)).map(|t| t.name.clone()).collect();
    // Sem lista de rotinas, elas entram quando as views também entram todas.
    let wanted_fn = |name: &str| match functions {
        Some(list) => list.iter().any(|x| x.split('(').next() == Some(name)),
        None => views.is_none(),
    };
    let routines: Vec<(String, bool)> = objects.functions.iter().filter(|f| wanted_fn(&f.name)).map(|f| (f.name.clone(), f.procedure)).collect();
    let mut plan = DumpPlan::default();
    let mut details: Vec<(String, TableDetail)> = Vec::new();
    for t in &table_names {
        details.push((t.clone(), meta::table_detail_on(conn, t)?));
    }

    // Geradores soltos (os da identidade são recriados pela própria coluna).
    let identity_gens: Vec<String> = if v3 {
        meta::query(conn, "SELECT TRIM(RDB$GENERATOR_NAME) FROM RDB$RELATION_FIELDS WHERE RDB$GENERATOR_NAME IS NOT NULL", vec![])?.into_iter().filter_map(|r| r.into_iter().next().flatten()).collect()
    } else {
        Vec::new()
    };
    // Sem lista de tabelas entram todos os geradores; com ela, só os que numeram colunas das tabelas escolhidas (por gatilho).
    let owned: Vec<String> = details.iter().flat_map(|(_, d)| d.columns.iter().filter_map(|c| c.auto_source.as_ref().and_then(|s| s.split('|').nth(1).map(str::to_string)))).collect();
    let generators: Vec<String> = objects.sequences.iter().map(|g| g.name.clone()).filter(|g| !identity_gens.contains(g) && (tables.is_none() || owned.contains(g))).collect();

    if clean {
        for (name, _) in routines.iter().rev() {
            let kind = if objects.functions.iter().any(|f| &f.name == name && f.procedure) { "PROCEDURE" } else { "FUNCTION" };
            plan.pre_data.push(guarded_drop(if kind == "PROCEDURE" { "RDB$PROCEDURES" } else { "RDB$FUNCTIONS" }, if kind == "PROCEDURE" { "RDB$PROCEDURE_NAME" } else { "RDB$FUNCTION_NAME" }, &format!("DROP {kind} {}", quote_ident(name)), name));
        }
        for v in view_names.iter().rev() {
            plan.pre_data.push(guarded_drop("RDB$RELATIONS", "RDB$RELATION_NAME", &format!("DROP VIEW {}", quote_ident(v)), v));
        }
        for (t, d) in &details {
            for c in d.constraints.iter().filter(|c| c.kind == "f") {
                plan.pre_data.push(guarded_drop("RDB$RELATION_CONSTRAINTS", "RDB$CONSTRAINT_NAME", &format!("ALTER TABLE {} DROP CONSTRAINT {}", quote_ident(t), quote_ident(&c.name)), &c.name));
            }
        }
        for (t, _) in details.iter().rev() {
            plan.pre_data.push(guarded_drop("RDB$RELATIONS", "RDB$RELATION_NAME", &format!("DROP TABLE {}", quote_ident(t)), t));
        }
        for g in &generators {
            plan.pre_data.push(guarded_drop("RDB$GENERATORS", "RDB$GENERATOR_NAME", &format!("DROP GENERATOR {}", quote_ident(g)), g));
        }
    }
    for g in &generators {
        plan.pre_data.push(format!("CREATE GENERATOR {};", quote_ident(g)));
        plan.objects += 1;
    }
    for (t, d) in &details {
        plan.pre_data.push(create_table(t, d));
        plan.data_tables.push(DumpTable { name: t.clone(), columns: d.columns.iter().filter(|c| c.generated.is_none()).map(|c| (c.name.clone(), c.data_type.clone())).collect() });
        plan.objects += 1;
    }
    for v in &view_names {
        let def = meta::view_detail_on(conn, v)?.definition;
        // As colunas da view vêm do que o servidor devolve (`RDB$RELATION_FIELDS`), então o texto basta.
        plan.pre_data.push(format!("CREATE VIEW {} AS\n{};", quote_ident(v), def.trim()));
        plan.objects += 1;
    }

    for (t, d) in &details {
        plan.post_data.extend(foreign_keys(t, d));
        for i in d.indexes.iter().filter(|i| !i.primary) {
            plan.post_data.push(format!("{};", i.definition));
            plan.objects += 1;
        }
    }
    // Valores dos geradores e das identidades: o dump leva o contador até onde estava.
    for g in &generators {
        let v = gen_value(conn, g)?;
        plan.post_data.push(format!("SET GENERATOR {} TO {v};", quote_ident(g)));
    }
    if v3 {
        for (t, d) in &details {
            let ids: Vec<String> = d.columns.iter().filter(|c| c.identity.is_some() && c.auto_source.is_none()).map(|c| c.name.clone()).collect();
            for col in ids {
                let rows = meta::query(
                    conn,
                    "SELECT TRIM(RDB$GENERATOR_NAME) FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME = ? AND RDB$FIELD_NAME = ?",
                    vec![rsfbclient::SqlType::Text(t.clone()), rsfbclient::SqlType::Text(col.clone())],
                )?;
                if let Some(g) = rows.first().and_then(|r| r.first().cloned().flatten()) {
                    let v = gen_value(conn, &g)?;
                    plan.post_data.push(format!("ALTER TABLE {} ALTER COLUMN {} RESTART WITH {};", quote_ident(t), quote_ident(&col), v + 1));
                }
            }
        }
    }
    for (name, _) in &routines {
        plan.post_data.push(block(&meta::routine_definition_on(conn, name)?));
        plan.objects += 1;
    }
    for (t, d) in &details {
        for g in &d.triggers {
            plan.post_data.push(block(&g.definition));
            plan.objects += 1;
        }
        let _ = t;
    }
    let _ = map_err;
    Ok(plan)
}

/// O valor como literal de `INSERT` do Firebird: número cru, booleano, texto entre aspas simples dobradas, binário em hexa.
pub fn literal(v: Option<&str>, sql_type: &str, boolean_ok: bool) -> String {
    let Some(v) = v else { return "NULL".into() };
    match sql_type.to_ascii_lowercase().as_str() {
        "smallint" | "integer" | "bigint" | "int128" | "numeric" | "decimal" | "float" | "double precision" => v.to_string(),
        "boolean" => {
            let on = v == "t" || v == "true";
            if boolean_ok { if on { "TRUE" } else { "FALSE" }.into() } else if on { "1".into() } else { "0".into() }
        }
        "blob" => {
            let hex = v.trim_start_matches("\\x");
            if hex.is_empty() { "''".into() } else { format!("x'{hex}'") }
        }
        _ => format!("'{}'", v.replace('\'', "''")),
    }
}
