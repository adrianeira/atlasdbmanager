import { useEffect, useState } from "react";
import { errorText, toAtlasError } from "../backend";
import { useT } from "../i18n";
import { SmallIcon } from "../icons";
import type { CellValue, ColumnDef } from "../model";

interface Props {
  table: string;
  columns: ColumnDef[];
  /** Os valores da linha que está sendo duplicada. */
  row: CellValue[];
  /** Insere a linha; rejeita com o erro do servidor (chave repetida, campo obrigatório...), que a janela mostra sem fechar. */
  onInsert: (values: CellValue[]) => Promise<void>;
  onClose: () => void;
}

/** Campos que o próprio banco gera (identidade, coluna gerada, sequência): ficam bloqueados e vazios, o banco preenche ao inserir. */
export const isAutoGenerated = (c: ColumnDef): boolean => !!c.identity || !!c.generated || /^nextval\(/i.test(c.default ?? "");

/** "Duplicar registro": mostra os campos da linha para conferir e editar antes de inserir a cópia. */
export function DuplicateRecordDialog({ table, columns, row, onInsert, onClose }: Props) {
  const t = useT();
  // Cada campo: o texto e se vale NULL. Campos automáticos entram vazios e bloqueados.
  const [fields, setFields] = useState(() => columns.map((c, i) => ({ value: isAutoGenerated(c) ? "" : row[i] ?? "", isNull: isAutoGenerated(c) || row[i] === null })));
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => { if (e.key === "Escape" && !busy) onClose(); };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose, busy]);

  const set = (i: number, p: Partial<(typeof fields)[number]>) => {
    setError(null);
    setFields((f) => f.map((x, j) => (j === i ? { ...x, ...p } : x)));
  };

  const insert = async () => {
    setBusy(true);
    setError(null);
    try {
      await onInsert(columns.map((c, i) => (isAutoGenerated(c) || fields[i].isNull ? null : fields[i].value)));
    } catch (e) {
      setError(errorText(toAtlasError(e)));
      setBusy(false);
    }
  };

  return (
    <div className="modal-overlay" role="presentation">
      <div className="modal dup-dialog" role="dialog" aria-label={t("dup.title")}>
        <div className="modal-header">
          <span className="modal-title">{t("dup.title")} — {table}</span>
          <button type="button" className="modal-close" aria-label={t("tab.close")} title={t("tab.close")} disabled={busy} onClick={onClose}><SmallIcon name="close" /></button>
        </div>
        <div className="modal-body">
          <div className="muted">{t("dup.intro")}</div>
          <div className="dup-grid">
            {columns.map((c, i) => {
              const auto = isAutoGenerated(c);
              const f = fields[i];
              const multiline = c.type === "json" || c.type === "jsonb" || c.type === "text";
              return (
                <div key={c.name} className="dup-row">
                  <label htmlFor={`dup-${i}`} className="dup-name" title={c.comment || undefined}>
                    {c.name}{c.key ? " 🔑" : ""}
                    <span className="muted dup-type">{c.castType ?? c.type}{c.notNull ? " · NOT NULL" : ""}</span>
                  </label>
                  {multiline
                    ? <textarea id={`dup-${i}`} className="field dup-input" rows={2} disabled={auto || f.isNull} value={f.value} spellCheck={false} placeholder={auto ? t("dup.auto") : f.isNull ? "NULL" : ""} onChange={(e) => set(i, { value: e.target.value })} />
                    : <input id={`dup-${i}`} className="field dup-input" disabled={auto || f.isNull} value={f.value} spellCheck={false} placeholder={auto ? t("dup.auto") : f.isNull ? "NULL" : ""} onChange={(e) => set(i, { value: e.target.value })} />}
                  <label className="check-row dup-null" title={auto ? t("dup.auto") : undefined}>
                    <input type="checkbox" checked={f.isNull} disabled={auto} onChange={(e) => set(i, { isNull: e.target.checked })} /><span>NULL</span>
                  </label>
                </div>
              );
            })}
          </div>
          {error && <div className="form-note form-note-warn dup-error">{error}</div>}
        </div>
        <div className="modal-footer">
          <span className="spacer" />
          <button type="button" className="btn btn-primary" disabled={busy} onClick={() => void insert()}>{busy ? t("dup.inserting") : t("dup.insert")}</button>
          <button type="button" className="btn" disabled={busy} onClick={onClose}>{t("opt.cancel")}</button>
        </div>
      </div>
    </div>
  );
}
