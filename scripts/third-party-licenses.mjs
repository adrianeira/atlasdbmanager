// Gera THIRD_PARTY_LICENSES.md com as licenças das dependências (Rust + npm de produção).
// Uso: node scripts/third-party-licenses.mjs   (precisa de cargo e de node_modules instalado)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const run = (cmd, args) => execFileSync(cmd, args, { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024, shell: process.platform === "win32" });

/* ---------- Rust (Cargo.lock: todas as plataformas) ---------- */
const meta = JSON.parse(run("cargo", ["metadata", "--format-version", "1", "--locked"]));
const workspace = new Set(meta.workspace_members);
const rust = meta.packages
  .filter((p) => !workspace.has(p.id))
  .map((p) => ({ name: p.name, version: p.version, license: p.license ?? (p.license_file ? `ver ${p.license_file}` : "?"), url: p.repository ?? "" }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

/* ---------- npm (só dependências de produção, transitivas) ---------- */
const tree = JSON.parse(run("npm", ["ls", "--omit=dev", "--all", "--json"]));
const npm = new Map();
const walk = (deps) => {
  for (const [name, info] of Object.entries(deps ?? {})) {
    const key = `${name}@${info.version}`;
    if (npm.has(key)) continue;
    let pkg = {};
    try { pkg = JSON.parse(readFileSync(join(root, "node_modules", name, "package.json"), "utf8")); } catch { /* sem package.json */ }
    const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url ?? "";
    npm.set(key, { name, version: info.version, license: pkg.license ?? "?", url: repo.replace(/^git\+/, "").replace(/\.git$/, "") });
    walk(info.dependencies);
  }
};
walk(tree.dependencies);
const js = [...npm.values()].sort((a, b) => a.name.localeCompare(b.name));

/* ---------- Saída ---------- */
const summary = (list) => {
  const count = new Map();
  for (const p of list) count.set(p.license, (count.get(p.license) ?? 0) + 1);
  return [...count].sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`).join("\n");
};
const table = (list) => list.map((p) => `| ${p.name} | ${p.version} | ${p.license} | ${p.url} |`).join("\n");

const md = `# Licenças de terceiros / Third-party licenses

Gerado por \`node scripts/third-party-licenses.mjs\` a partir do \`Cargo.lock\` e do \`package-lock.json\`.
Generated by \`node scripts/third-party-licenses.mjs\` from \`Cargo.lock\` and \`package-lock.json\`.

O Atlas DB Manager é distribuído sob a licença MIT (veja [LICENSE](LICENSE)). As dependências abaixo
mantêm as licenças dos seus autores; o texto completo de cada uma está no respectivo pacote/repositório.
Atlas DB Manager is MIT-licensed (see [LICENSE](LICENSE)). The dependencies below keep their authors'
licenses; each full license text ships with the package/repository.

A lista Rust inclui dependências de todas as plataformas (Windows, Linux e macOS) presentes no \`Cargo.lock\`.
The Rust list includes dependencies for every platform (Windows, Linux and macOS) in \`Cargo.lock\`.

## Resumo / Summary

### Rust (${rust.length} pacotes / packages)

| Licença / License | Pacotes / Packages |
|---|---|
${summary(rust)}

### npm — produção / production (${js.length} pacotes / packages)

| Licença / License | Pacotes / Packages |
|---|---|
${summary(js)}

## npm

| Pacote / Package | Versão / Version | Licença / License | Repositório / Repository |
|---|---|---|---|
${table(js)}

## Rust

| Pacote / Package | Versão / Version | Licença / License | Repositório / Repository |
|---|---|---|---|
${table(rust)}
`;
writeFileSync(join(root, "THIRD_PARTY_LICENSES.md"), md);
console.log(`THIRD_PARTY_LICENSES.md: ${rust.length} Rust + ${js.length} npm`);
